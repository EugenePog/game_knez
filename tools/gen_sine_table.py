#!/usr/bin/env python3
"""Generate sim/src/Knez.Sim/Numerics/SineTable.cs — the quarter-wave sine table behind FixMath.Sin/Cos.

The sim never computes trigonometry with floating point (ADR-0002). This script does, once, offline; the
resulting integers are committed and are the definition of sin/cos in the game. Re-running it must produce
an identical file — FixTrigTests.Table_MatchesTheGeneratorFormula checks every entry exactly, and a changed
table changes golden hashes, so treat a diff as a rule change.

257 entries: sin(k * 90° / 256) * 65536 rounded to nearest, k = 0..256 (no entry is near a rounding tie, so
other platforms' math libraries give the same table). SineTable.QuarterSin interpolates linearly between
entries; the total error against the true sine is at most 1.70/65536 over all 65536 angles.

Usage: python3 tools/gen_sine_table.py
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "sim" / "src" / "Knez.Sim" / "Numerics" / "SineTable.cs"
STEPS = 256


def main() -> None:
    values = [round(math.sin(k * (math.pi / 2) / STEPS) * 65536) for k in range(STEPS + 1)]
    assert values[0] == 0 and values[-1] == 65536
    rows = []
    for i in range(0, len(values), 12):
        rows.append("            " + ", ".join(str(v) for v in values[i:i + 12]) + ",")
    body = "\n".join(rows)
    OUT.write_text(f"""// <auto-generated> by tools/gen_sine_table.py — do not edit by hand. </auto-generated>
namespace Knez.Sim.Numerics
{{
    /// <summary>
    /// Quarter-wave sine table: entry k = sin(k × 90° / {STEPS}) in 1/65536 units (ADR-0002), and the interpolating
    /// lookup over it. The array is private so no code can write to it.
    /// </summary>
    internal static class SineTable
    {{
        /// <summary><see cref="Angle"/> units in a quarter turn.</summary>
        internal const int QuarterTurn = 16384;

        private const int StepBits = 6; // 16384 units per quarter turn / {STEPS} entries
        private const int StepMask = (1 << StepBits) - 1;

        private static readonly int[] QuarterWave =
        {{
{body}
        }};

        /// <summary>sin of <paramref name="units"/> in 0..16384 (one quarter turn), in raw Fix units.</summary>
        internal static int QuarterSin(int units)
        {{
            int index = units >> StepBits;
            int fraction = units & StepMask;
            if (fraction == 0)
            {{
                return QuarterWave[index];
            }}

            // The table rises monotonically, so the product is non-negative and the shift truncates toward zero.
            return QuarterWave[index] + (((QuarterWave[index + 1] - QuarterWave[index]) * fraction) >> StepBits);
        }}
    }}
}}
""", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(values)} entries)")


if __name__ == "__main__":
    main()
