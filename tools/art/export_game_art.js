#!/usr/bin/env node
/*
 * Export Game_knez art for Unity: PNG sprites + Unity .meta files + a JSON manifest.
 *
 *   node tools/art/export_game_art.js            # writes game/Assets/Knez/Art/Resources/
 *   CHROME=/path/to/chrome node tools/art/...     # if Chrome is not in the default place
 *
 * Sources are the design generators in docs/design/art (paperdoll.js — people, objects.js — buildings and map
 * objects). SVGs are rasterised by headless Chrome (no npm packages needed). Existing .meta files are kept, so
 * GUIDs never change; new ones get a GUID derived from the asset path. See docs/art-assets.md.
 *
 * The output is a Unity Resources folder: the view loads the manifest and sprites at run time by the manifest's own
 * paths (Resources.Load("Tokens/tok_...")), with no scene or Inspector wiring (docs/art-pipeline.md).
 */
'use strict';
var fs = require('fs');
var path = require('path');
var os = require('os');
var crypto = require('crypto');
var cp = require('child_process');

var ROOT = path.resolve(__dirname, '..', '..');
var PD = require(path.join(ROOT, 'docs/design/art/paperdoll.js'));
var OB = require(path.join(ROOT, 'docs/design/art/objects.js'));
var OUT_REL = 'game/Assets/Knez/Art/Resources';   // a Resources folder: manifest paths are Resources.Load paths
var OUT = path.join(ROOT, OUT_REL);

// ---------------------------------------------------------------- conventions
var TOKEN = { ppu: 200, viewBox: [-64, -96, 128, 160], pivot: [0.5, 0.4] };   // 1 SVG unit = 1 cm; body centre at (0,0)
var PORTRAIT = { scale: 1.5, viewBox: [0, 0, 240, 352], pivot: [0.5, 12 / 352] };   // feet at y = 340
var MAP = { ppu: 64 };                                                           // plan: 10 SVG units = 1 m
var ISO = { scale: 2 };

var SIDES = ['clan', 'ruler', 'bandits'];
var KIT_IDS = Object.keys(PD.KITS);
var VARIANTS = 4;

// who wears a kit on each side (unnamed men; Retainers are listed separately)
function fighterRole(side, kit) {
  if (side === 'bandits') return { role: 'bandit', exp: kit.indexOf('-padded') > 0 || kit.indexOf('-mail') > 0 ? 'experienced' : 'new' };
  if (kit.indexOf('-mail') > 0) return side === 'ruler' ? { role: 'retainer', exp: 'professional' } : { role: 'warrior', exp: 'experienced' };
  if (kit.indexOf('sword') === 0) return { role: 'warrior', exp: 'experienced' };
  if (kit.indexOf('-padded') > 0) return { role: 'militia', exp: 'experienced' };
  return { role: 'militia', exp: 'new' };
}

// ---------------------------------------------------------------- jobs
var jobs = [];      // { file, svg, w, h, kind }
var manifest = {
  description: 'Game_knez art for the Unity view, generated by tools/art/export_game_art.js from docs/design/art ' +
    '(paperdoll.js, objects.js). Do not edit by hand; change the generators and re-export. Contract: docs/art-assets.md.',
  version: 1,
  conventions: {
    worldUnit: 'metre: sim metres are Unity units, X east, Y north (FixViewExtensions)',
    tokens: { folder: 'Tokens', pixelsPerUnit: TOKEN.ppu, sizeMetres: [TOKEN.viewBox[2] / 100, TOKEN.viewBox[3] / 100], pivot: TOKEN.pivot,
      pivotIs: 'the body centre (sim position)', drawnFacing: 90,
      rotation: 'drawn facing north (+Y, sim facing 90 degrees): z rotation = facing - 90',
      note: 'shield is the side colour and pattern; no shield means a civilian' },
    portraits: { folder: 'Portraits', pixelsPerUnit: 100, pivot: PORTRAIT.pivot, pivotIs: 'between the feet', use: 'UI only' },
    map: { folder: 'Map', pixelsPerUnit: MAP.ppu, pivot: [0.5, 0.5], pivotIs: 'the centre of the footprint (size)', north: 'up',
      walls: 'axis-aligned rectangles in metres, centre relative to the pivot (Y north) and size; kind as MapDef walls' },
    objects: { folder: 'Objects', pixelsPerUnit: 100, pivot: [0.5, 0.5], use: 'UI cards (3/4 view)' }
  },
  sides: {},
  fighters: [],
  heroes: [],
  civilians: [],
  map: []
};
SIDES.forEach(function (s) {
  var S = PD.SIDES[s];
  manifest.sides[s] = { name: S.name, shield: [PD.col(S.c1), PD.col(S.c2)], pattern: S.pattern, militiaBand: PD.col(S.band) };
});

function svgSized(svg, w, h) { return svg.replace('<svg ', '<svg width="' + w + '" height="' + h + '" '); }
function tokenJob(name, spec, title) {
  var vb = TOKEN.viewBox, w = Math.round(vb[2] / 100 * TOKEN.ppu), h = Math.round(vb[3] / 100 * TOKEN.ppu);
  jobs.push({ file: 'Tokens/' + name + '.png', kind: 'token', w: w, h: h,
    svg: svgSized(PD.top(spec, { viewBox: vb.join(' '), title: title }), w, h) });
  return 'Tokens/' + name;
}
function portraitJob(name, spec, title) {
  var vb = PORTRAIT.viewBox, w = Math.round(vb[2] * PORTRAIT.scale), h = Math.round(vb[3] * PORTRAIT.scale);
  jobs.push({ file: 'Portraits/' + name + '.png', kind: 'portrait', w: w, h: h, svg: svgSized(PD.front(spec, { title: title }), w, h) });
  return 'Portraits/' + name;
}

// ---- unnamed fighters: side × kit × variants
SIDES.forEach(function (side) {
  KIT_IDS.forEach(function (kit) {
    var rw = fighterRole(side, kit);
    for (var v = 0; v < VARIANTS; v++) {
      var spec = PD.make({ role: rw.role, side: side, kit: kit, exp: rw.exp, seed: 1000 + SIDES.indexOf(side) * 211 + KIT_IDS.indexOf(kit) * 37 + v * 7 });
      var base = side + '_' + kit + '_' + v;
      var entry = { side: side, kit: kit, role: rw.role, experience: rw.exp, variant: v,
        token: tokenJob('tok_' + base, spec, kit + ', ' + side + ' ' + v) };
      if (v === 0) entry.portrait = portraitJob('por_' + base, spec, kit + ', ' + side);
      manifest.fighters.push(entry);
    }
  });
});

// ---- Retainers: named from the design roster, then generic ones per side and kit
PD.ROSTER.filter(function (e) { return e.make.role === 'retainer'; }).forEach(function (e) {
  var spec = PD.rosterSpec(e), name = 'hero_' + e.id;
  manifest.heroes.push({ id: e.id, title: e.title, sub: e.sub, side: e.side, kit: spec.kit, experience: spec.exp, named: true,
    token: tokenJob('tok_' + name, spec, e.title), portrait: portraitJob('por_' + name, spec, e.title) });
});
[['clan', 4], ['ruler', 2]].forEach(function (sv) {
  ['sword-shield-mail', 'axe-shield-mail', 'sword-shield-padded'].forEach(function (kit) {
    for (var v = 0; v < sv[1]; v++) {
      var exp = v % 2 ? 'elite' : 'professional';
      var spec = PD.make({ role: 'retainer', side: sv[0], kit: kit, exp: exp, seed: 3000 + KIT_IDS.indexOf(kit) * 41 + v * 13 + (sv[0] === 'ruler' ? 500 : 0) });
      var name = 'hero_' + sv[0] + '_' + kit + '_' + v;
      manifest.heroes.push({ id: name, side: sv[0], kit: kit, experience: exp, named: false, variant: v,
        token: tokenJob('tok_' + name, spec, 'Retainer ' + kit), portrait: portraitJob('por_' + name, spec, 'Retainer ' + kit) });
    }
  });
});

// ---- civilians: the design presets, then generic men and women per side
PD.PEOPLE.forEach(function (e) {
  var spec = PD.rosterSpec(e), name = 'civ_' + e.id;
  manifest.civilians.push({ id: e.id, title: e.title, sub: e.sub, side: e.side, sex: spec.sex, wealth: spec.wealth, style: spec.style || null,
    preset: true, token: tokenJob('tok_' + name, spec, e.title), portrait: portraitJob('por_' + name, spec, e.title) });
});
['ruler', 'clan'].forEach(function (side) {
  ['citizen', 'woman'].forEach(function (role) {
    for (var v = 0; v < VARIANTS; v++) {
      var spec = PD.make({ role: role, side: side, wealth: v % 3, seed: 5000 + v * 17 + (role === 'woman' ? 300 : 0) + (side === 'clan' ? 900 : 0) });
      var name = 'civ_' + side + '_' + (role === 'woman' ? 'f' : 'm') + '_' + v;
      manifest.civilians.push({ id: name, side: side, sex: spec.sex, wealth: spec.wealth, style: spec.style || null, preset: false, variant: v,
        token: tokenJob('tok_' + name, spec, role + ' ' + side), portrait: portraitJob('por_' + name, spec, role + ' ' + side) });
    }
  });
});

// ---- map objects: top-down sprite (64 px/m, pivot at the footprint centre) + 3/4 view for UI
OB.OBJECTS.forEach(function (o) {
  var m = Math.min(2.4, Math.max(0.8, 0.6 + o.h * 0.3));
  var W = o.size[0] + 2 * m, D = o.size[1] + 2 * m;
  var pw = Math.round(W * MAP.ppu), ph = Math.round(D * MAP.ppu);
  jobs.push({ file: 'Map/map_' + o.id + '.png', kind: 'map', w: pw, h: ph, svg: svgSized(OB.plan(o.id, { margin: m, sim: false, ground: false }), pw, ph) });
  var iso = OB.view(o.id, { pad: 6 });
  var vb = /viewBox="([-\d.]+) ([-\d.]+) ([-\d.]+) ([-\d.]+)"/.exec(iso);
  var iw = Math.round(+vb[3] * ISO.scale), ih = Math.round(+vb[4] * ISO.scale);
  jobs.push({ file: 'Objects/obj_' + o.id + '.png', kind: 'object', w: iw, h: ih, svg: svgSized(iso, iw, ih) });
  var walls = OB.walls(o.id).map(function (r) {
    return { center: [round3(r[0] + r[2] / 2 - o.size[0] / 2), round3(-(r[1] + r[3] / 2 - o.size[1] / 2))], size: [round3(r[2]), round3(r[3])],
      kind: o.sim === 'house' ? 'house' : 'obstacle' };
  });
  manifest.map.push({ id: o.id, name: o.name, group: o.group, groupName: OB.GROUPS[o.group], size: o.size, height: o.h, sim: o.sim,
    where: o.where, note: o.note, sprite: 'Map/map_' + o.id, spriteSizeMetres: [round3(pw / MAP.ppu), round3(ph / MAP.ppu)],
    walls: walls, view: 'Objects/obj_' + o.id });
});
function round3(v) { return Math.round(v * 1000) / 1000; }

// ---------------------------------------------------------------- rasterise with headless Chrome
function findChrome() {
  var c = [process.env.CHROME, '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    '/Applications/Chromium.app/Contents/MacOS/Chromium', '/usr/bin/google-chrome', '/usr/bin/chromium', '/usr/bin/chromium-browser'];
  for (var i = 0; i < c.length; i++) if (c[i] && fs.existsSync(c[i])) return c[i];
  throw new Error('Chrome not found: set CHROME=/path/to/chrome');
}
var tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'knez-art-'));
var page = '<!doctype html><meta charset="utf-8"><body><script id="jobs" type="application/json">' +
  JSON.stringify(jobs.map(function (j) { return { f: j.file, w: j.w, h: j.h, b: Buffer.from(j.svg, 'utf8').toString('base64') }; })) +
  '</script><script>(async function () {' +
  'var jobs = JSON.parse(document.getElementById("jobs").textContent), out = {};' +
  'for (var i = 0; i < jobs.length; i++) { var j = jobs[i], img = new Image(); img.src = "data:image/svg+xml;base64," + j.b; await img.decode();' +
  'var c = document.createElement("canvas"); c.width = j.w; c.height = j.h; c.getContext("2d").drawImage(img, 0, 0, j.w, j.h);' +
  'out[j.f] = c.toDataURL("image/png").slice(22); }' +
  'document.getElementById("jobs").remove(); var p = document.createElement("pre"); p.id = "out"; p.textContent = JSON.stringify(out); document.body.appendChild(p);' +
  '})();</script>';
var htmlPath = path.join(tmp, 'render.html');
fs.writeFileSync(htmlPath, page);
var dom = cp.execFileSync(findChrome(), ['--headless=new', '--disable-gpu', '--no-first-run', '--no-default-browser-check',
  '--user-data-dir=' + path.join(tmp, 'profile'), '--virtual-time-budget=600000', '--dump-dom', 'file://' + htmlPath],
  { maxBuffer: 1 << 30, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
var m = /<pre id="out">([\s\S]*?)<\/pre>/.exec(dom);
if (!m) throw new Error('Chrome returned no images');
var pngs = JSON.parse(m[1]);
fs.rmSync(tmp, { recursive: true, force: true });

// ---------------------------------------------------------------- write files and .meta
function guid(rel) { return crypto.createHash('md5').update('game_knez:' + rel).digest('hex'); }
function spriteId(rel) { return crypto.createHash('md5').update('sprite:' + rel).digest('hex').slice(0, 16) + '0800000000000000'; }
function folderMeta(rel) {
  return 'fileFormatVersion: 2\nguid: ' + guid(rel) + '\nfolderAsset: yes\nDefaultImporter:\n  externalObjects: {}\n  userData: \n  assetBundleName: \n  assetBundleVariant: \n';
}
function textMeta(rel) {
  return 'fileFormatVersion: 2\nguid: ' + guid(rel) + '\nTextScriptImporter:\n  externalObjects: {}\n  userData: \n  assetBundleName: \n  assetBundleVariant: \n';
}
function platform(target) {
  return '  - serializedVersion: 4\n    buildTarget: ' + target + '\n    maxTextureSize: 2048\n    resizeAlgorithm: 0\n    textureFormat: -1\n' +
    '    textureCompression: 1\n    compressionQuality: 50\n    crunchedCompression: 0\n    allowsAlphaSplitting: 0\n    overridden: 0\n' +
    '    ignorePlatformSupport: 0\n    androidETC2FallbackOverride: 0\n    forceMaximumCompressionQuality_BC6H_BC7: 0\n';
}
function textureMeta(rel, ppu, pivot, mips) {
  return 'fileFormatVersion: 2\nguid: ' + guid(rel) + '\nTextureImporter:\n  internalIDToNameTable: []\n  externalObjects: {}\n  serializedVersion: 13\n' +
    '  mipmaps:\n    mipMapMode: 0\n    enableMipMap: ' + (mips ? 1 : 0) + '\n    sRGBTexture: 1\n    linearTexture: 0\n    fadeOut: 0\n    borderMipMap: 0\n' +
    '    mipMapsPreserveCoverage: 0\n    alphaTestReferenceValue: 0.5\n    mipMapFadeDistanceStart: 1\n    mipMapFadeDistanceEnd: 3\n' +
    '  bumpmap:\n    convertToNormalMap: 0\n    externalNormalMap: 0\n    heightScale: 0.25\n    normalMapFilter: 0\n    flipGreenChannel: 0\n' +
    '  isReadable: 0\n  streamingMipmaps: 0\n  streamingMipmapsPriority: 0\n  vTOnly: 0\n  ignoreMipmapLimit: 0\n  grayScaleToAlpha: 0\n' +
    '  generateCubemap: 6\n  cubemapConvolution: 0\n  seamlessCubemap: 0\n  textureFormat: 1\n  maxTextureSize: 2048\n' +
    '  textureSettings:\n    serializedVersion: 2\n    filterMode: 1\n    aniso: 1\n    mipBias: 0\n    wrapU: 1\n    wrapV: 1\n    wrapW: 1\n' +
    '  nPOTScale: 0\n  lightmap: 0\n  compressionQuality: 50\n  spriteMode: 1\n  spriteExtrude: 1\n  spriteMeshType: 1\n  alignment: 9\n' +
    '  spritePivot: {x: ' + pivot[0] + ', y: ' + pivot[1] + '}\n  spritePixelsToUnits: ' + ppu + '\n  spriteBorder: {x: 0, y: 0, z: 0, w: 0}\n' +
    '  spriteGenerateFallbackPhysicsShape: 0\n  alphaUsage: 1\n  alphaIsTransparency: 1\n  spriteTessellationMethod: 0\n' +
    '  spriteTessellationDetail: -1\n  spriteGeometrySubdivision: -1\n  textureType: 8\n  textureShape: 1\n  singleChannelComponent: 0\n' +
    '  flipbookRows: 1\n  flipbookColumns: 1\n  maxTextureSizeSet: 0\n  compressionQualitySet: 0\n  textureFormatSet: 0\n  ignorePngGamma: 0\n' +
    '  applyGammaDecoding: 0\n  swizzle: 50462976\n  cookieLightType: 0\n  platformSettings:\n' + platform('DefaultTexturePlatform') + platform('Standalone') +
    '  spriteSheet:\n    serializedVersion: 2\n    sprites: []\n    outline: []\n    customData: \n    physicsShape: []\n    bones: []\n' +
    '    spriteID: ' + spriteId(rel) + '\n    internalID: 0\n    vertices: []\n    indices: \n    edges: []\n    weights: []\n' +
    '    secondaryTextures: []\n    spriteCustomMetadata:\n      entries: []\n    nameFileIdTable: {}\n  mipmapLimitGroupName: \n' +
    '  pSDRemoveMatte: 0\n  userData: \n  assetBundleName: \n  assetBundleVariant: \n';
}
function writeMeta(abs, text) { if (!fs.existsSync(abs + '.meta')) fs.writeFileSync(abs + '.meta', text); }
function ensureFolder(rel) {
  var abs = path.join(ROOT, rel);
  if (!fs.existsSync(abs)) fs.mkdirSync(abs, { recursive: true });
  writeMeta(abs, folderMeta(rel));
}

ensureFolder('game/Assets/Knez/Art');
ensureFolder(OUT_REL);
['Tokens', 'Portraits', 'Map', 'Objects'].forEach(function (f) { ensureFolder(OUT_REL + '/' + f); });

var SETTINGS = {
  token: { ppu: TOKEN.ppu, pivot: TOKEN.pivot, mips: true },
  portrait: { ppu: 100, pivot: [0.5, Math.round(PORTRAIT.pivot[1] * 10000) / 10000], mips: false },
  map: { ppu: MAP.ppu, pivot: [0.5, 0.5], mips: true },
  object: { ppu: 100, pivot: [0.5, 0.5], mips: false }
};
var written = 0;
jobs.forEach(function (j) {
  var data = pngs[j.file];
  if (!data) throw new Error('missing render: ' + j.file);
  var abs = path.join(OUT, j.file), rel = path.relative(ROOT, abs).split(path.sep).join('/');
  fs.writeFileSync(abs, Buffer.from(data, 'base64'));
  var st = SETTINGS[j.kind];
  writeMeta(abs, textureMeta(rel, st.ppu, st.pivot, st.mips));
  written++;
});

// palette: every named colour of the people generator, plus the map colours
var palette = { description: 'Named colours of the Game_knez art (docs/design/art-style.md). People: dyes, pigments, metals; map: materials.',
  people: {}, map: OB.COLORS };
Object.keys(PD.COLORS).forEach(function (k) { palette.people[k] = { hex: PD.COLORS[k].hex, name: PD.COLORS[k].name, group: PD.COLORS[k].group }; });
fs.writeFileSync(path.join(OUT, 'palette.json'), JSON.stringify(palette, null, 2) + '\n');
writeMeta(path.join(OUT, 'palette.json'), textMeta(OUT_REL + '/palette.json'));
fs.writeFileSync(path.join(OUT, 'art-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
writeMeta(path.join(OUT, 'art-manifest.json'), textMeta(OUT_REL + '/art-manifest.json'));

console.log('sprites: ' + written + ' (fighters ' + manifest.fighters.length + ', heroes ' + manifest.heroes.length +
  ', civilians ' + manifest.civilians.length + ', map objects ' + manifest.map.length + ') -> ' + path.relative(ROOT, OUT));
